import streamlit as st
import pandas as pd
import joblib

# Load trained model
model = joblib.load("model/credit_card_default_model.pkl")

st.set_page_config(
    page_title="Credit Card Default Prediction",
    page_icon="💳",
    layout="wide"
)

st.title("💳 Credit Card Default Prediction")
st.write("Enter customer details to predict the likelihood of credit card default.")

st.divider()

# Customer information
st.subheader("👤 Customer Information")

col1, col2, col3 = st.columns(3)

with col1:
    limit_bal = st.number_input(
        "Credit Limit",
        min_value=0,
        value=50000
    )

with col2:
    sex = st.selectbox(
        "Sex",
        [1, 2],
        format_func=lambda x: "Male" if x == 1 else "Female"
    )

with col3:
    education = st.selectbox(
        "Education",
        [1, 2, 3, 4],
        format_func=lambda x: {
            1: "Graduate School",
            2: "University",
            3: "High School",
            4: "Others"
        }[x]
    )

col1, col2, col3 = st.columns(3)

with col1:
    marriage = st.selectbox(
        "Marital Status",
        [1, 2, 3],
        format_func=lambda x: {
            1: "Married",
            2: "Single",
            3: "Others"
        }[x]
    )

with col2:
    age = st.number_input(
        "Age",
        min_value=18,
        max_value=100,
        value=30
    )

with col3:
    pay_0 = st.number_input(
        "Repayment Status (September)",
        min_value=-2,
        max_value=8,
        value=0
    )

st.divider()

st.subheader("📅 Repayment History")

col1, col2, col3 = st.columns(3)

with col1:
    pay_2 = st.number_input("Repayment Status (August)", -2, 8, 0)
    pay_3 = st.number_input("Repayment Status (July)", -2, 8, 0)

with col2:
    pay_4 = st.number_input("Repayment Status (June)", -2, 8, 0)
    pay_5 = st.number_input("Repayment Status (May)", -2, 8, 0)

with col3:
    pay_6 = st.number_input("Repayment Status (April)", -2, 8, 0)

st.divider()

st.subheader("💰 Billing & Payment Information")

st.write("Enter the latest six months of billing amounts and payment amounts.")

bill_cols = st.columns(3)

with bill_cols[0]:
    bill_amt1 = st.number_input("Bill Amount 1", value=50000)
    bill_amt2 = st.number_input("Bill Amount 2", value=48000)

with bill_cols[1]:
    bill_amt3 = st.number_input("Bill Amount 3", value=45000)
    bill_amt4 = st.number_input("Bill Amount 4", value=42000)

with bill_cols[2]:
    bill_amt5 = st.number_input("Bill Amount 5", value=40000)
    bill_amt6 = st.number_input("Bill Amount 6", value=38000)

pay_cols = st.columns(3)

with pay_cols[0]:
    pay_amt1 = st.number_input("Payment Amount 1", value=5000)
    pay_amt2 = st.number_input("Payment Amount 2", value=5000)

with pay_cols[1]:
    pay_amt3 = st.number_input("Payment Amount 3", value=5000)
    pay_amt4 = st.number_input("Payment Amount 4", value=5000)

with pay_cols[2]:
    pay_amt5 = st.number_input("Payment Amount 5", value=5000)
    pay_amt6 = st.number_input("Payment Amount 6", value=5000)

st.divider()

# Prediction
if st.button("🔍 Predict Default Risk", use_container_width=True):

    input_data = pd.DataFrame([[
        limit_bal,
        sex,
        education,
        marriage,
        age,
        pay_0,
        pay_2,
        pay_3,
        pay_4,
        pay_5,
        pay_6,
        bill_amt1,
        bill_amt2,
        bill_amt3,
        bill_amt4,
        bill_amt5,
        bill_amt6,
        pay_amt1,
        pay_amt2,
        pay_amt3,
        pay_amt4,
        pay_amt5,
        pay_amt6
    ]], columns=[
        "LIMIT_BAL",
        "SEX",
        "EDUCATION",
        "MARRIAGE",
        "AGE",
        "PAY_0",
        "PAY_2",
        "PAY_3",
        "PAY_4",
        "PAY_5",
        "PAY_6",
        "BILL_AMT1",
        "BILL_AMT2",
        "BILL_AMT3",
        "BILL_AMT4",
        "BILL_AMT5",
        "BILL_AMT6",
        "PAY_AMT1",
        "PAY_AMT2",
        "PAY_AMT3",
        "PAY_AMT4",
        "PAY_AMT5",
        "PAY_AMT6"
    ])

    prediction = model.predict(input_data)[0]
    probability = model.predict_proba(input_data)[0][1]

    st.divider()

    st.subheader("📊 Prediction Result")

    col1, col2 = st.columns(2)

    with col1:
        st.metric(
            "Default Probability",
            f"{probability * 100:.2f}%"
        )

    with col2:
        if prediction == 1:
            st.error("🔴 High Risk of Default")
        else:
            st.success("🟢 Lower Risk of Default")

    st.progress(float(probability))

    st.caption(
        "This prediction is generated by a machine learning model "
        "trained on historical credit-card customer data."
    )